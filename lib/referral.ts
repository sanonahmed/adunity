/**
 * Referral rules shared by the server route and the client panel.
 *
 * Deliberately dependency-free and side-effect-free: code parsing, link
 * building and label formatting must behave identically wherever they run.
 *
 * Attribution comes from Telegram's *signed* `start_param`, never from a
 * query string the client could edit. Values look like `ref_AB12CD34`.
 */

/** Telegram only allows [A-Za-z0-9_-] in a start parameter. */
export const REFERRAL_START_PREFIX = "ref_";

/** 8 characters from a 31-symbol alphabet — unambiguous, ~2^40 space. */
export const REFERRAL_CODE_LENGTH = 8;

/** How many referred users the dashboard lists. */
export const REFERRAL_RECENT_LIMIT = 8;

/** Width of the activity chart, in calendar days (today included). */
export const REFERRAL_ACTIVITY_DAYS = 14;

/* ── referral revenue share ──────────────────────────────────────
   Referral earnings are a percentage of actual ad revenue generated
   by referred users. Invite attribution alone is not a cash balance;
   earnings remain unavailable until revenue data is recorded.
   ─────────────────────────────────────────────────────────────── */

/** Referrer share of verified ad revenue generated by referred users. */
export const REFERRAL_COMMISSION_PERCENT = 25;

export type ReferralRecord = {
  /** 1-based join order for this referrer: the oldest invite is 1. */
  index: number;
  joinedAt: string;
};

export type ReferralActivityDay = {
  /** Calendar day, `YYYY-MM-DD`. */
  date: string;
  count: number;
};

export type ReferralActivity = {
  /** `REFERRAL_ACTIVITY_DAYS` buckets, oldest first, zero-filled. */
  days: ReferralActivityDay[];
  today: number;
  last7Days: number;
  /** The 7 days before `last7Days`, for a week-over-week comparison. */
  previous7Days: number;
  last30Days: number;
  /** Distinct days with at least one invite in the last 30 days. */
  activeDays: number;
  bestDay: ReferralActivityDay | null;
  lastInviteAt: string | null;
  /** Consecutive days ending today (or yesterday) with at least one invite. */
  streakDays: number;
};

export type ReferralStats = ReferralActivity & {
  /** Position among accounts that have invited someone; null before the first. */
  rank: number | null;
  /** How many accounts that leaderboard contains. */
  referrers: number;
};

export type ReferralRewards = {
  commissionPercent: number;
  /** BDT share of referred users' recorded ad revenue; null until revenue is tracked. */
  earnedBdt: number | null;
};

export type ReferralSummary = {
  code: string;
  invitedCount: number;
  /** When this account was first recorded by the server (ISO 8601). */
  joinedAt: string;
  recent: ReferralRecord[];
  stats: ReferralStats;
  rewards: ReferralRewards;
};

export type ReferralApiSuccess = { ok: true; referral: ReferralSummary };

export type ReferralApiFailure = {
  ok: false;
  error:
    | "server_not_configured"
    | "missing_init_data"
    | "invalid_json"
    | "bad_signature"
    | "expired"
    | "missing_hash"
    | "missing_auth_date"
    | "malformed_user"
    | "store_error";
};

export type ReferralApiResponse = ReferralApiSuccess | ReferralApiFailure;

/** `ref_AB12CD34` -> `"AB12CD34"`; anything else -> null. */
export function parseReferralCode(startParam: string | null | undefined): string | null {
  if (!startParam) return null;

  const trimmed = startParam.trim();
  if (!trimmed.toLowerCase().startsWith(REFERRAL_START_PREFIX)) return null;

  const code = trimmed.slice(REFERRAL_START_PREFIX.length).toUpperCase();
  if (code.length !== REFERRAL_CODE_LENGTH) return null;
  if (!/^[A-Z0-9]+$/.test(code)) return null;

  return code;
}

/**
 * Builds the shareable Telegram link for an invite code:
 *
 *   `https://t.me/<bot>?startapp=ref_<code>`
 *
 * This form opens the bot's *main* Mini App (the one behind its menu button)
 * and hands it `ref_<code>` as the signed `start_param`.
 *
 * The `https://t.me/<bot>/<short_name>?startapp=...` form is deliberately not
 * produced. It only resolves when a Mini App was registered under that exact
 * short name with BotFather `/newapp`; when it was not, Telegram answers
 * "bot application not found" and every invite link is dead. The bot-only form
 * has no such failure mode, because it never names an app.
 *
 * Returns null when there is nothing valid to link to.
 */
export function buildInviteLink(
  code: string,
  botUsername: string | null | undefined,
): string | null {
  const bot = botUsername?.trim().replace(/^@/, "");
  const cleanCode = code?.trim().toUpperCase();
  if (!bot || !cleanCode) return null;

  /* A code that `parseReferralCode` would reject yields a link whose
     `start_param` is silently ignored, so refuse to build one. */
  if (cleanCode.length !== REFERRAL_CODE_LENGTH || !/^[A-Z0-9]+$/.test(cleanCode)) {
    return null;
  }

  return `https://t.me/${bot}?startapp=${REFERRAL_START_PREFIX}${cleanCode}`;
}

/** `AB12CD34` -> `AB12 CD34`, for easier reading aloud. */
export function formatReferralCode(code: string): string {
  const clean = code.trim().toUpperCase();
  if (clean.length !== REFERRAL_CODE_LENGTH) return clean;
  return `${clean.slice(0, 4)} ${clean.slice(4)}`;
}

const DAY_MS = 86_400_000;

/** `YYYY-MM-DD` for an ISO timestamp, or null when it cannot be parsed. */
function dayKey(value: string): string | null {
  const time = Date.parse(value);
  if (!Number.isFinite(time)) return null;
  return new Date(time).toISOString().slice(0, 10);
}

/** Calendar day `offset` days before `now`, as `YYYY-MM-DD`. */
function dayKeyFrom(now: Date, offset: number): string {
  return new Date(now.getTime() - offset * DAY_MS).toISOString().slice(0, 10);
}

/**
 * Turns raw invite timestamps into every activity figure the dashboard shows.
 *
 * Pure and deterministic for a given `now`, so the numbers can be unit-tested
 * and recomputed identically on the server and in tests. Days are grouped in
 * **UTC**, the only timezone the server can trust: a referrer in UTC+13 and one
 * in UTC-8 both see the same buckets rather than two different totals.
 *
 * Unparseable timestamps are ignored rather than throwing, so one bad row can
 * never blank the whole dashboard.
 */
export function summariseActivity(
  timestamps: readonly string[],
  now: Date = new Date(),
  windowDays: number = REFERRAL_ACTIVITY_DAYS,
): ReferralActivity {
  const counts = new Map<string, number>();
  let lastInviteAt: string | null = null;

  for (const stamp of timestamps) {
    const key = dayKey(stamp);
    if (!key) continue;

    counts.set(key, (counts.get(key) ?? 0) + 1);
    if (lastInviteAt === null || Date.parse(stamp) > Date.parse(lastInviteAt)) {
      lastInviteAt = stamp;
    }
  }

  const window = Number.isFinite(windowDays) ? Math.max(1, Math.floor(windowDays)) : REFERRAL_ACTIVITY_DAYS;
  const days: ReferralActivityDay[] = [];
  for (let offset = window - 1; offset >= 0; offset -= 1) {
    const date = dayKeyFrom(now, offset);
    days.push({ date, count: counts.get(date) ?? 0 });
  }

  function totalBetween(from: number, to: number): number {
    let sum = 0;
    for (let offset = from; offset <= to; offset += 1) {
      sum += counts.get(dayKeyFrom(now, offset)) ?? 0;
    }
    return sum;
  }

  /* Earliest day wins a tie, so the "best day" label never flickers between
     two equally busy days. */
  let bestDay: ReferralActivityDay | null = null;
  for (const date of [...counts.keys()].sort()) {
    const count = counts.get(date) ?? 0;
    if (bestDay === null || count > bestDay.count) bestDay = { date, count };
  }

  /* A streak stays alive until today ends, so it is measured from today when
     today already has an invite and from yesterday otherwise. */
  let streakDays = 0;
  for (let offset = counts.has(dayKeyFrom(now, 0)) ? 0 : 1; counts.has(dayKeyFrom(now, offset)); offset += 1) {
    streakDays += 1;
  }

  return {
    days,
    today: counts.get(dayKeyFrom(now, 0)) ?? 0,
    last7Days: totalBetween(0, 6),
    previous7Days: totalBetween(7, 13),
    last30Days: totalBetween(0, 29),
    activeDays: Array.from({ length: 30 }, (_, offset) => dayKeyFrom(now, offset)).filter(
      (date) => (counts.get(date) ?? 0) > 0,
    ).length,
    bestDay,
    lastInviteAt,
    streakDays,
  };
}

/**
 * Calculates a referrer's share from actual referred-user ad revenue.
 * Null is returned when revenue is not available; invite counts are never
 * treated as a cash balance.
 */
export function computeReferralEarnings(referredAdRevenueBdt: number | null): ReferralRewards {
  const validRevenue =
    referredAdRevenueBdt !== null &&
    Number.isFinite(referredAdRevenueBdt) &&
    referredAdRevenueBdt >= 0
      ? referredAdRevenueBdt
      : null;

  return {
    commissionPercent: REFERRAL_COMMISSION_PERCENT,
    earnedBdt:
      validRevenue === null
        ? null
        : Math.round((validRevenue * REFERRAL_COMMISSION_PERCENT) / 100 * 100) / 100,
  };
}
